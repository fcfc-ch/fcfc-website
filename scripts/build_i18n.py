"""
Builds the German, French and Italian versions of the site from the English index.html.

    index.html                 English source (edit this one)
    translations/de.json       {"lang": "de", "strings": {"English text": "Deutsch", ...}}
    translations/fr.json
    translations/it.json
    translations/_keep.json    strings that are identical in every language (names, codes)

Output: de/index.html, fr/index.html, it/index.html

Every visible text node and the alt / aria-label / title / meta description attributes are
looked up by their English text (whitespace-normalised). Anything without a translation stays
in English and is listed at the end of the run, so new English copy never breaks a page.

Runs automatically from .github/workflows/build-i18n.yml when index.html or a translation
changes. Local run:  pip install beautifulsoup4 && python scripts/build_i18n.py
"""

import json
import os
import re
import sys

from bs4 import BeautifulSoup, Comment, NavigableString

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
LANGS = ["de", "fr", "it"]
ATTRS = ["alt", "aria-label", "title"]
SKIP_PARENTS = {"script", "style"}


def norm(s):
    return " ".join(s.split())


def load(lang):
    with open(os.path.join(ROOT, "translations", f"{lang}.json"), encoding="utf-8") as f:
        data = json.load(f)
    return {norm(k): v for k, v in data["strings"].items()}


def rel_fix(url):
    """Make a root-relative asset path work from a one-level-deep language folder."""
    if not url or re.match(r"^(?:[a-z]+:|#|/|\.\./)", url, re.I):
        return url
    return "../" + url


def build(lang, src_html, strings, keep):
    soup = BeautifulSoup(src_html, "html.parser")
    missing = []

    soup.html["lang"] = lang

    # Visible text
    for node in list(soup.find_all(string=True)):
        if isinstance(node, Comment) or node.parent.name in SKIP_PARENTS:
            continue
        key = norm(node)
        if not key:
            continue
        if key in strings:
            lead = " " if node[:1].isspace() else ""
            trail = " " if node[-1:].isspace() else ""
            node.replace_with(NavigableString(lead + strings[key] + trail))
        elif key not in keep and key not in missing:
            missing.append(key)

    # Attributes
    for el in soup.find_all(True):
        for a in ATTRS:
            v = el.get(a)
            if isinstance(v, str) and norm(v):
                if norm(v) in strings:
                    el[a] = strings[norm(v)]
                elif norm(v) not in keep and norm(v) not in missing:
                    missing.append(norm(v))
    desc = soup.find("meta", attrs={"name": "description"})
    if desc and norm(desc.get("content", "")) in strings:
        desc["content"] = strings[norm(desc["content"])]
    elif desc:
        missing.append("[meta description]")

    # Asset paths and data base path
    for el in soup.find_all(["link", "script", "img", "source", "video"]):
        for a in ("href", "src", "poster"):
            if el.get(a) and not (el.name == "link" and el.get("rel") and "alternate" in el.get("rel")):
                el[a] = rel_fix(el[a])
    base = soup.find("meta", attrs={"name": "fcfc-base"})
    if base:
        base["content"] = "../"

    # Language switcher
    for a in soup.select(".lang-switch a[data-lang]"):
        target = a["data-lang"]
        a["href"] = "../" if target == "en" else f"../{target}/"
        if target == lang:
            a["aria-current"] = "true"
        elif a.has_attr("aria-current"):
            del a["aria-current"]

    return str(soup), missing


def main():
    with open(os.path.join(ROOT, "index.html"), encoding="utf-8") as f:
        src = f.read()
    with open(os.path.join(ROOT, "translations", "_keep.json"), encoding="utf-8") as f:
        keep = {norm(k) for k in json.load(f)}

    for lang in LANGS:
        html, missing = build(lang, src, load(lang), keep)
        out_dir = os.path.join(ROOT, lang)
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, "index.html"), "w", encoding="utf-8") as f:
            note = "<!-- Generated by scripts/build_i18n.py from index.html — do not edit by hand. -->"
            # keep <!DOCTYPE html> first so browsers stay in standards mode
            html = re.sub(r"(<!DOCTYPE html>)", r"\1\n" + note, html, count=1, flags=re.I)
            f.write(html)
        print(f"{lang}: written, {len(missing)} untranslated string(s)")
        for m in missing:
            print(f"   - {m[:110]}")


if __name__ == "__main__":
    sys.exit(main())
